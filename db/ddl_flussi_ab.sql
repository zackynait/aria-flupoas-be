-- FLUPER A/B - staging degli invii e dei file caricati.
-- Eseguire una sola volta nello schema Oracle usato dal backend.

CREATE TABLE FLUPER_INVIO (
    ID_INVIO       VARCHAR2(36)   NOT NULL,
    FLUSSO         CHAR(1)         NOT NULL,
    PERIODO        CHAR(7)         NOT NULL,
    TIPO_INVIO     VARCHAR2(10)   DEFAULT 'TOTALE' NOT NULL,
    STATO          VARCHAR2(20)   NOT NULL,
    DATA_RICEZIONE TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FLUPER_INVIO PRIMARY KEY (ID_INVIO),
    CONSTRAINT CK_FLUPER_INVIO_FLUSSO CHECK (FLUSSO IN ('A', 'B')),
    CONSTRAINT CK_FLUPER_INVIO_PERIODO CHECK (REGEXP_LIKE(PERIODO, '^[0-9]{4}-(0[1-9]|1[0-2])$')),
    CONSTRAINT CK_FLUPER_INVIO_TIPO CHECK (TIPO_INVIO IN ('TOTALE', 'PARZIALE')),
    CONSTRAINT CK_FLUPER_INVIO_STATO CHECK (STATO IN ('RICEVUTO', 'SCARTATO'))
);

CREATE INDEX IX_FLUPER_INVIO_PERIODO ON FLUPER_INVIO (FLUSSO, PERIODO, DATA_RICEZIONE);

CREATE TABLE FLUPER_FILE_INVIO (
    ID_FILE      VARCHAR2(36)  NOT NULL,
    ID_INVIO     VARCHAR2(36)  NOT NULL,
    NOME_FILE    VARCHAR2(255) NOT NULL,
    CONTENT_TYPE VARCHAR2(255),
    DIMENSIONE   NUMBER(12)    NOT NULL,
    CONSTRAINT PK_FLUPER_FILE_INVIO PRIMARY KEY (ID_FILE),
    CONSTRAINT FK_FLUPER_FILE_INVIO FOREIGN KEY (ID_INVIO) REFERENCES FLUPER_INVIO (ID_INVIO),
    CONSTRAINT CK_FLUPER_FILE_SIZE CHECK (DIMENSIONE BETWEEN 0 AND 20971520)
);

CREATE INDEX IX_FLUPER_FILE_INVIO ON FLUPER_FILE_INVIO (ID_INVIO);

CREATE TABLE FLUPER_ANOMALIA (
    ID_ANOMALIA  VARCHAR2(36)   NOT NULL,
    ID_INVIO     VARCHAR2(36)   NOT NULL,
    CODICE       VARCHAR2(40)   NOT NULL,
    DESCRIZIONE  VARCHAR2(1000) NOT NULL,
    NUMERO_RIGA  NUMBER(10),
    CONSTRAINT PK_FLUPER_ANOMALIA PRIMARY KEY (ID_ANOMALIA),
    CONSTRAINT FK_FLUPER_ANOMALIA FOREIGN KEY (ID_INVIO) REFERENCES FLUPER_INVIO (ID_INVIO)
);

CREATE INDEX IX_FLUPER_ANOMALIA_INVIO ON FLUPER_ANOMALIA (ID_INVIO);

-- Staging delle righe valide. DATI_JSON contiene solo le colonne del tracciato
-- inviate al flusso, escludendo sempre COGNOME, NOME, SESSO e DATA_NASCITA.
-- CODICE_FISCALE resta come chiave necessaria di identificazione del record.
CREATE TABLE FLUPER_RIGA_INVIO (
    ID_RIGA         VARCHAR2(36) NOT NULL,
    ID_INVIO        VARCHAR2(36) NOT NULL,
    NUMERO_RIGA     NUMBER(10)   NOT NULL,
    FLUSSO          CHAR(1)      NOT NULL,
    PERIODO         VARCHAR2(6)  NOT NULL,
    CODICE_ENTE     VARCHAR2(20) NOT NULL,
    CODICE_FISCALE  VARCHAR2(16) NOT NULL,
    PROGRESSIVO     VARCHAR2(9)  NOT NULL,
    DATI_JSON       CLOB         NOT NULL,
    CONSTRAINT PK_FLUPER_RIGA_INVIO PRIMARY KEY (ID_RIGA),
    CONSTRAINT FK_FLUPER_RIGA_INVIO FOREIGN KEY (ID_INVIO) REFERENCES FLUPER_INVIO (ID_INVIO),
    CONSTRAINT CK_FLUPER_RIGA_FLUSSO CHECK (FLUSSO IN ('A', 'B')),
    CONSTRAINT CK_FLUPER_RIGA_JSON CHECK (DATI_JSON IS JSON)
);

CREATE INDEX IX_FLUPER_RIGA_INVIO ON FLUPER_RIGA_INVIO (ID_INVIO, NUMERO_RIGA);
CREATE INDEX IX_FLUPER_RIGA_CF ON FLUPER_RIGA_INVIO (FLUSSO, PERIODO, CODICE_ENTE, CODICE_FISCALE);
